DRIFT_TOLERANCE = 0.05  # 5 points
# Tier names follow eval-coverage-common.json. Mapping onto data (documented, not hidden):
#   canonical    = held-out rows whose tier is canonical (corpus canonical + synthetic clean)
#   exemplar     = held-out rows in the paraphrase tier (natural exemplar-style phrasing; NOT
#                  the training exemplars themselves, which are never scored)
#   adversarial  = held-out rows in the adversarial tier (corpus boundary + synthetic adversarial/ambiguous)
#   perturbation = eval_option_d.PERTURBATIONS (paraphrase/casual/verbose/negation variants)
TIERS = ("canonical", "exemplar", "adversarial", "perturbation")
_HELDOUT_TIER_FOR = {"canonical": "canonical", "exemplar": "paraphrase", "adversarial": "adversarial"}
BASELINE_FILE_HASHES = {
    "classify_intent.py": ROOT / "scripts" / "classify_intent.py",
    "semantic_scorer.py": ROOT / "scripts" / "semantic_scorer.py",
    "intent_exemplars.json": ROOT / "config" / "intent_exemplars.json",
    "semantic_thresholds.json": ROOT / "config" / "semantic_thresholds.json",
    "real_user_corpus.json": ROOT / "tests" / "data" / "real_user_corpus.json",
    "production_synthetic.json": ROOT / "tests" / "data" / "production_synthetic.json",
}


def _sha(path: Path) -> str | None:
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else None


def current_source_hashes() -> dict[str, str | None]:
    return {name: _sha(p) for name, p in BASELINE_FILE_HASHES.items()}


def _git_commit() -> str | None:
    import subprocess
    try:
        out = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                             text=True, timeout=5)
        return out.stdout.strip() or None if out.returncode == 0 else None
    except Exception:
        return None


def score_heldout_results() -> list[dict]:
    items = eval_option_d.load_heldout_items()
    res = eval_option_d.run_population(items, "text", "label")
    for r, it in zip(res, items):
        r["difficulty"] = it["difficulty"]
    return res


def confusion_matrix(results: list[dict]) -> dict[str, dict[str, int]]:
    """matrix[actual][predicted] over all 8 intents (+ 'other' for anything else)."""
    classes = list(heldout.INTENTS)
    m = {a: {p: 0 for p in classes + ["other"]} for a in classes}
    for r in results:
        a, p = r["label"], r["predicted"]
        if a in m:
            m[a][p if p in classes else "other"] += 1
    return m


def tier_matrix(heldout_results: list[dict], perturb_results: list[dict]) -> dict:
    """matrix[intent][tier] = {support, correct, recall}; every intent x tier cell present."""
    m = {i: {t: {"support": 0, "correct": 0, "recall": None} for t in TIERS} for i in heldout.INTENTS}

    def add(intent, tier, ok):
        if intent in m:
            c = m[intent][tier]
            c["support"] += 1
            c["correct"] += int(ok)

    for r in heldout_results:
        for tier, ho_tier in _HELDOUT_TIER_FOR.items():
            if r["difficulty"] == ho_tier:
                add(r["label"], tier, r["predicted"] == r["label"])
    for r in perturb_results:
        add(r["label"], "perturbation", r["predicted"] == r["label"])
    for row in m.values():
        for c in row.values():
            c["recall"] = round(c["correct"] / c["support"], 3) if c["support"] else None
    return m


def empty_cells(matrix: dict) -> list[tuple[str, str]]:
    return [(i, t) for i, row in matrix.items() for t, c in row.items() if c["support"] == 0]


def drift_check(live_per_class: dict, baseline_per_class: dict,
                min_support: int = eval_option_d.MIN_CLASS_SUPPORT,
                tolerance: float = DRIFT_TOLERANCE) -> list[dict]:
    """Classes whose precision or recall moved more than `tolerance` (either direction).

    Only evaluated when BOTH live and baseline support >= min_support; thinner classes are
    reported as `skipped_low_support` by drift_report, never silently passed as stable.
    """
    out = []
    for c in heldout.INTENTS:
        live, base = live_per_class.get(c), baseline_per_class.get(c)
        if live is None or base is None:
            out.append({"class": c, "metric": "missing", "delta": None})
            continue
        if min(live["support"], base["support"]) < min_support:
            continue
        for metric in ("precision", "recall"):
            lv, bv = live[metric], base[metric]
            if lv is None or bv is None:
                if lv != bv:
                    out.append({"class": c, "metric": metric, "baseline": bv, "live": lv, "delta": None})
                continue
            if abs(lv - bv) > tolerance + 1e-9:
                out.append({"class": c, "metric": metric, "baseline": bv, "live": lv,
                            "delta": round(lv - bv, 3)})
    return out


def skipped_low_support(live_per_class: dict, baseline_per_class: dict,
                        min_support: int = eval_option_d.MIN_CLASS_SUPPORT) -> list[str]:
    return [c for c in heldout.INTENTS
            if c in live_per_class and c in baseline_per_class
            and min(live_per_class[c]["support"], baseline_per_class[c]["support"]) < min_support]


def load_baseline(path: Path = eval_option_d.BASELINE_PATH) -> dict:
    return json.loads(path.read_text())


def stale_baseline_files(baseline: dict) -> list[str]:
    """Source files whose hash differs from what the baseline was recorded against."""
    recorded = baseline.get("baseline_meta", {}).get("source_hashes", {})
    now = current_source_hashes()
    return [k for k, v in now.items() if recorded.get(k) != v]


def update_baseline() -> Path:
    """Recompute and overwrite the committed baseline (only reachable via --update-baseline)."""
    eval_option_d.main(["--write-baseline"])
    path = eval_option_d.BASELINE_PATH
    base = load_baseline(path)
    held = score_heldout_results()
    perturb = eval_option_d.run_population(eval_option_d.PERTURBATIONS, "text", "label")
    base["confusion_matrix"] = confusion_matrix(held)
    base["tier_matrix"] = tier_matrix(held, perturb)
    base["baseline_meta"] = {
        "created": datetime.now(timezone.utc).isoformat(),
        "git_commit": _git_commit(),  # null when the tree is not a git checkout
        "source_hashes": current_source_hashes(),
        "tiers": list(TIERS),
        "drift_tolerance": DRIFT_TOLERANCE,
    }
    path.write_text(json.dumps(base, indent=2, ensure_ascii=False) + "\n")
    return path


