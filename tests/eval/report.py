def stale_manifest_entries() -> list[str]:
    """Artifacts whose current hash differs from the committed manifest (or manifest missing)."""
    if not MANIFEST_PATH.exists():
        return list(MANIFEST_ARTIFACTS)
    recorded = json.loads(MANIFEST_PATH.read_text()).get("hashes", {})
    return [k for k, v in current_manifest().items() if recorded.get(k) != v]


