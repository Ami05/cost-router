DEFAULT_PROD_EVENTS = Path.home() / ".claude" / "plugins" / "local" / "cost-router" / "data" / "routing_events.jsonl"
DEDUPE_RULE = (
    "Denominator = events with type=='intent' only. Duplicate emission (T12): check_routing.py "
    "(--event reset) and classify_intent.py each append an intent event per prompt; the "
    "check_routing twin has no 'source' key. Per (session_id, ts) key keep every event that has "
    "'source', and keep source-less events only for the surplus beyond the number of "
    "source-bearing events (unpaired twins)."
)


class ProdEventsMissing(RuntimeError):
    pass


def load_prod_intent_events(path: Path | None = None) -> list[dict]:
    """Read-only load of type=='intent' events; raises ProdEventsMissing (never skips)."""
    path = Path(path) if path else DEFAULT_PROD_EVENTS
    if not path.exists():
        raise ProdEventsMissing(
            f"production events file not found: {path}. Pass --prod-file <path> to override; "
            "the weighted coverage report will not silently skip."
        )
    events = []
    with open(path, encoding="utf-8") as f:  # read-only
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                e = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(e, dict) and e.get("type") == "intent" and isinstance(e.get("intent"), str):
                events.append(e)
    return events


def dedupe_intent_events(events: list[dict]) -> list[dict]:
    """Apply DEDUPE_RULE (see T12 report). Order-stable."""
    groups: dict[tuple, list[dict]] = {}
    for e in events:
        groups.setdefault((e.get("session_id"), e.get("ts")), []).append(e)
    kept = []
    for evs in groups.values():
        with_src = [e for e in evs if "source" in e]
        without = [e for e in evs if "source" not in e]
        kept.extend(with_src)
        kept.extend(without[len(with_src):])
    return kept


def production_weighted_report(prod_events: list[dict], per_class: dict) -> dict:
    """Weight held-out per-class recall by production intent counts.

    weight_c = deduped production intent events of class c / total deduped intent events.
    weighted_accuracy = sum_c weight_c * recall_c over classes with held-out support > 0.
    Production classes with no held-out recall are listed in `uncovered`; their weight is
    excluded from the numerator and reported as `uncovered_weight` (denominator stays all intents).
    """
    from collections import Counter
    deduped = dedupe_intent_events(prod_events)
    counts = Counter(e["intent"] for e in deduped)
    total = sum(counts.values())
    if total == 0:
        raise ProdEventsMissing("no type=='intent' events in production file; cannot weight")
    rows, weighted, uncovered_weight, uncovered = {}, 0.0, 0.0, []
    for c, n in sorted(counts.items()):
        st = per_class.get(c)
        w = n / total
        rec = st["recall"] if st and st.get("support", 0) > 0 else None
        rows[c] = {"prod_count": n, "weight": round(w, 4), "heldout_recall": rec,
                   "heldout_support": st["support"] if st else 0}
        if rec is None:
            uncovered_weight += w
            uncovered.append(c)
        else:
            weighted += w * rec
    return {
        "dedupe_rule": DEDUPE_RULE,
        "raw_intent_events": len(prod_events),
        "deduped_intent_events": total,
        "per_class": rows,
        "weighted_accuracy": round(weighted, 4),
        "uncovered_weight": round(uncovered_weight, 4),
        "uncovered": uncovered,
        "heldout_classes_without_prod_events": sorted(set(heldout.INTENTS) - set(counts)),
    }


def format_matrix(cm: dict) -> str:
    cols = list(next(iter(cm.values())))
    lines = ["actual \\ predicted | " + " | ".join(c[:10] for c in cols)]
    for a, row in cm.items():
        lines.append(f"{a:<22}| " + " | ".join(f"{row[c]:>10}" for c in cols))
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description="Confusion matrix + drift check vs committed baseline")
    ap.add_argument("--update-baseline", action="store_true",
                    help="explicitly overwrite tests/eval_results/option_d_eval.json")
    ap.add_argument("--update-manifest", action="store_true",
                    help="explicitly rewrite tests/eval_results/artifact_hashes.json")
    ap.add_argument("--prod-file", type=Path, default=None,
                    help="routing_events.jsonl for the production-weighted report (read-only)")
    ap.add_argument("--prod-weighted", action="store_true",
                    help="print the production-weighted coverage report (fails if the file is missing)")
    args = ap.parse_args(argv)
    if args.update_manifest:
        print(f"Manifest updated: {update_manifest()}")
        return 0
    if args.prod_weighted:
        try:
            events = load_prod_intent_events(args.prod_file)
        except ProdEventsMissing as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 2
        live_pc = eval_option_d.score_population(score_heldout_results())["per_class"]
        rep = production_weighted_report(events, live_pc)
        print(json.dumps(rep, indent=2))
        return 0
    if args.update_baseline:
        print(f"Baseline updated: {update_baseline()}")
        return 0

    base = load_baseline()
    held = score_heldout_results()
    perturb = eval_option_d.run_population(eval_option_d.PERTURBATIONS, "text", "label")
    live = eval_option_d.score_population(held)["per_class"]
    print(format_matrix(confusion_matrix(held)))
    tm = tier_matrix(held, perturb)
    print("\nintent x tier recall (support):")
    for i, row in tm.items():
        print(f"  {i:<24}" + "  ".join(f"{t}={row[t]['recall']}({row[t]['support']})" for t in TIERS))
    drift = drift_check(live, base["heldout"]["score"]["per_class"])
    stale = stale_baseline_files(base)
    for d in drift:
        print("DRIFT:", d)
    for c in empty_cells(tm):
        print("EMPTY CELL:", c)
    if stale:
        print("Baseline recorded against different sources:", stale, "(use --update-baseline after review)")
    return 1 if (drift or empty_cells(tm)) else 0


if __name__ == "__main__":
    raise SystemExit(main())
